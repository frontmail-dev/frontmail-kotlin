import com.vanniktech.maven.publish.JavadocJar
import com.vanniktech.maven.publish.KotlinJvm
import org.jetbrains.kotlin.gradle.dsl.JvmTarget
import org.jetbrains.kotlin.gradle.dsl.KotlinVersion

plugins {
    alias(libs.plugins.kotlin.jvm)
    alias(libs.plugins.maven.publish)
    alias(libs.plugins.bcv)
}

val versionName = providers.gradleProperty("VERSION_NAME").get()
group = providers.gradleProperty("GROUP").get()
version = versionName

java {
    // Android-friendly bytecode; `release` also stops JDK 12+ APIs from sneaking in.
    sourceCompatibility = JavaVersion.VERSION_11
    targetCompatibility = JavaVersion.VERSION_11
}

kotlin {
    explicitApi()
    // Don't force a newer stdlib on apps than kotlinx-serialization already needs (Kotlin 2.2+ apps).
    coreLibrariesVersion = "2.3.20"
    compilerOptions {
        jvmTarget.set(JvmTarget.JVM_11)
        // Metadata readable by older compilers (a compiler reads metadata one version ahead).
        apiVersion.set(KotlinVersion.KOTLIN_2_2)
        languageVersion.set(KotlinVersion.KOTLIN_2_2)
        freeCompilerArgs.add("-Xjdk-release=11")
        allWarningsAsErrors.set(true)
    }
}

tasks.withType<JavaCompile>().configureEach {
    options.release.set(11)
}

// The version lives only in gradle.properties; the SDK reads it from this generated source.
val generateVersion by tasks.registering {
    val out = layout.buildDirectory.dir("generated/version/kotlin")
    val v = versionName
    inputs.property("version", v)
    outputs.dir(out)
    doLast {
        val file = out.get().file("dev/frontmail/FrontmailVersion.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |// Generated by the `generateVersion` Gradle task from gradle.properties – do not edit.
            |package dev.frontmail
            |
            |/** Version of the Frontmail Kotlin SDK. */
            |public object FrontmailVersion {
            |    /** SDK version, e.g. `0.1.0`. */
            |    public const val CURRENT: String = "$v"
            |}
            |
            """.trimMargin(),
        )
    }
}

sourceSets.main {
    kotlin.srcDir(generateVersion)
}

dependencies {
    api(libs.kotlinx.coroutines.core)
    api(libs.kotlinx.serialization.json)

    testImplementation(kotlin("test"))
    testImplementation(libs.kotlinx.coroutines.test)
    testImplementation(platform(libs.junit.bom))
    testImplementation(libs.junit.jupiter)
    testRuntimeOnly(libs.junit.platform.launcher)
}

tasks.test {
    useJUnitPlatform()
    systemProperty("frontmail.version", versionName)
    testLogging {
        events("failed")
        exceptionFormat = org.gradle.api.tasks.testing.logging.TestExceptionFormat.FULL
    }
}

mavenPublishing {
    configure(KotlinJvm(javadocJar = JavadocJar.Empty(), sourcesJar = true))
    // Coordinates come from gradle.properties: GROUP:POM_ARTIFACT_ID:VERSION_NAME.
    publishToMavenCentral(automaticRelease = true)

    // Sign only when a key is configured (CI: ORG_GRADLE_PROJECT_signingInMemoryKey*), so
    // `publishToMavenLocal` works on developer machines. `-PskipSigning` forces it off.
    val hasSigningKey =
        providers.gradleProperty("signingInMemoryKey").isPresent ||
            providers.gradleProperty("signing.keyId").isPresent
    if (hasSigningKey && !providers.gradleProperty("skipSigning").isPresent) {
        signAllPublications()
    }

    pom {
        name.set("Frontmail Kotlin SDK")
        description.set(
            "Send emails from Android and Kotlin/JVM apps through Frontmail templates with a public key – " +
                "coroutines, retries with idempotency, message status and Cloudflare Turnstile helpers.",
        )
        inceptionYear.set("2026")
        url.set("https://github.com/frontmail-dev/frontmail-kotlin")
        licenses {
            license {
                name.set("MIT License")
                url.set("https://opensource.org/licenses/MIT")
                distribution.set("repo")
            }
        }
        developers {
            developer {
                id.set("frontmail-dev")
                name.set("Frontmail")
                url.set("https://github.com/frontmail-dev")
            }
        }
        scm {
            url.set("https://github.com/frontmail-dev/frontmail-kotlin")
            connection.set("scm:git:https://github.com/frontmail-dev/frontmail-kotlin.git")
            developerConnection.set("scm:git:ssh://git@github.com/frontmail-dev/frontmail-kotlin.git")
        }
        issueManagement {
            system.set("GitHub")
            url.set("https://github.com/frontmail-dev/frontmail-kotlin/issues")
        }
    }
}
